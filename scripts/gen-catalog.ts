// Writes src/content/catalog.ts from the full content. Run: npm run catalog (also runs before every build).
import { writeFileSync } from 'node:fs';
import { worlds } from '../src/content/index';
import { toOutline } from '../src/content/outline';

const body = JSON.stringify(worlds.map(toOutline), null, 1);
writeFileSync(
  new URL('../src/content/catalog.ts', import.meta.url),
  `// Generated by scripts/gen-catalog.ts. Do not edit by hand; run npm run catalog.\nimport type { WorldOutline } from './outline';\n\nexport const catalog: WorldOutline[] = ${body};\n`,
);
console.log(`catalog: ${worlds.length} worlds, ${worlds.reduce((n, w) => n + w.chapters.reduce((m, c) => m + c.lessons.length, 0), 0)} lessons`);
